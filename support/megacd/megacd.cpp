static int need_reset=0;
static uint8_t has_command = 0;

// Physical CD state machine
enum PhysicalCDState {
	PCD_IDLE,       // No media detected
	PCD_LOADING,    // TOC being loaded
	PCD_OPENING,    // Signal door open/close to BIOS
	PCD_READY       // Disc ready, BIOS in control
};

static pthread_t toc_thread;
static volatile bool toc_thread_active = false;   // true if thread is running/joined-pending
static volatile bool toc_thread_finished = false; // set by worker when done
static CDROM_TrackInfo toc_buffer[100];
static int toc_result_count = 0;
static int toc_job_id = 0;        // Current desired job ID
static int toc_thread_job_id = 0; // Job ID of the running thread

static void* toc_worker(void* arg)
{
	(void)arg;
	DebugLog("[MISTER] TOC Thread: Starting read_cdrom_toc...\n");
	toc_result_count = read_cdrom_toc(0, toc_buffer, 99);
	DebugLog("[MISTER] TOC Thread: Finished. Count = %d\n", toc_result_count);
	
	toc_thread_finished = true;
	return NULL;
}

void mcd_poll()
{
	static uint32_t poll_timer = 0;
	static uint8_t last_req = 255;
	static uint8_t adj = 0;
	static uint32_t hw_poll_timer = 0;
	
	// Physical CD state
	static PhysicalCDState cd_state = PCD_IDLE;
	static uint32_t load_timer = 0;
	static bool load_attempted = false;
	static bool was_menu_open = false; // Track menu state for OSD restore

	// Throttle hardware polling to every 500ms to prevent UI freeze
	if (!hw_poll_timer || CheckTimer(hw_poll_timer))
	{
		hw_poll_timer = GetTimer(500);

		switch (cd_state)
		{
		case PCD_IDLE:
			// No media → ensure NO_DISC status
			if (!hasCDROMMedia(0))
			{
				if (cdd.loaded)
				{
					cdd.Unload();
					Info("CD Removed", 2000);
					DebugLog("[MISTER] CD removed, unloading\n");
				}
				
				// CRITICAL: Set NO_DISC if not loaded
				// Reset() puts STOP, but we need NO_DISC when no media
				if (!cdd.loaded && cdd.status != CD_STAT_NO_DISC)
				{
					cdd.status = CD_STAT_NO_DISC;
				}
				
				load_attempted = false;
			}
			// Media detected → start loading
			else if (!load_attempted && 
			         (getCDROMType(0) == DISC_MEGACD || getCDROMType(0) == DISC_UNKNOWN))
			{
				cd_state = PCD_LOADING;
				toc_job_id++; // New insertion = new job
				load_timer = GetTimer(100); // Small debounce
				cdd.status = CD_STAT_NO_DISC; // Keep NO_DISC during load
				Info("Disc Inserted...", 2000);
				printf("\x1b[32m[MISTER] ===== DISC INSERTION DETECTED =====\x1b[0m\n");
				printf("[MISTER] State: IDLE → LOADING\n");
				printf("[MISTER] cdd.status = NO_DISC (0x%02X)\n", cdd.status);
				DebugLog("[MISTER] State: IDLE → LOADING\n");
			}
			break;
			
		case PCD_LOADING:
			// Media removed during loading
			if (!hasCDROMMedia(0))
			{
				cd_state = PCD_IDLE;
				load_attempted = false;
				DebugLog("[MISTER] Load aborted - media removed\n");
				
				// Keep thread running/active until it finishes naturally, 
				// we will clean it up in IDLE state or next polling cycle if finished.
				break;
			}
			
			// Wait for debounce timer
			if (CheckTimer(load_timer))
			{
				// Check for stale thread
				if (toc_thread_active && toc_thread_job_id != toc_job_id)
				{
					if (toc_thread_finished)
					{
						DebugLog("[MISTER] Stale TOC thread finished. Discarding result.\n");
						pthread_join(toc_thread, NULL);
						toc_thread_active = false;
						// Now loop will continue and start new thread below
					}
					else
					{
						// Still running on old job. Must wait.
						// Status is still "Checking Disc..." (or we should update it?)
						// Info("Busy...", 1);
						break; // Wait for next poll
					}
				}

				// Start thread if not active
				if (!toc_thread_active)
				{
					Info("Checking Disc...", 30000); // Long timeout
					DebugLog("[MISTER] Starting TOC background thread (Job %d)...\n", toc_job_id);
					
					toc_thread_finished = false;
					if (pthread_create(&toc_thread, NULL, toc_worker, NULL) == 0)
					{
						toc_thread_active = true;
						toc_thread_job_id = toc_job_id;
					}
					else
					{
						DebugLog("[MISTER] Failed to create TOC thread! Fallback to blocking.\n");
						// Fallback: doing it blocking or just retry
						toc_result_count = read_cdrom_toc(0, toc_buffer, 99);
						toc_thread_finished = true; // Pretend thread finished
						toc_thread_active = false; // We didn't really start a thread (or failed)
						
						// Handle immediate result below
						if (toc_result_count > 0)
						{
							mcd_set_image(0, "", toc_buffer, toc_result_count);
						}
					}
				}
				else
				{
					// Thread is running. Check if we need to restore OSD message.
					bool is_menu_open = is_menu();
					if (was_menu_open && !is_menu_open)
					{
						Info("Checking Disc...", 30000); // Re-assert message
					}
					else if (!is_menu_open && CheckTimer(load_timer)) // Periodic check (using same timer variable or create new one?)
					{
						// Actually load_timer is used for debounce at start, but here it's expired.
						// We can use a different trick: check if Info message is gone?
						// Impossible to check OSD content directly easily.
						// But re-asserting every few seconds is safe.
						Info("Checking Disc...", 30000); 
						load_timer = GetTimer(2000); // Wait 2s before re-asserting to avoid flicker
					}
					was_menu_open = is_menu_open;
				}
				
				// Check if thread finished (and it is inevitabley the correct job if we are here)
				if (toc_thread_active && toc_thread_finished)
				{
					pthread_join(toc_thread, NULL);
					toc_thread_active = false;
					
					if (toc_result_count > 0)
					{
						DebugLog("[MISTER] TOC Thread success. Mounting image...\n");
						mcd_set_image(0, "", toc_buffer, toc_result_count);
					}
					else
					{
						DebugLog("[MISTER] TOC Thread failed (count <= 0).\n");
						// Just retry? Or go back to IDLE?
						// If we stay in LOADING, we might loop.
						// Let's retry after a delay.
						load_timer = GetTimer(500);
					}
				}

				if (cdd.loaded)
				{
					// Success! Signal OPEN first (BIOS needs to see door open/close)
					cdd.status = CD_STAT_OPEN;
					cdd.latency = 0;
					cd_state = PCD_OPENING;
					load_attempted = true;
					load_timer = GetTimer(500); // Hold OPEN for 500ms
					
					printf("\x1b[32m[MISTER] ===== TOC LOADED SUCCESSFULLY =====\x1b[0m\n");
					printf("[MISTER] State: LOADING → OPENING\n");
					printf("[MISTER] cdd.status = OPEN (0x%02X) - signaling door\n", cdd.status);
					printf("[MISTER] cdd.loaded = %d\n", cdd.loaded);
					DebugLog("[MISTER] TOC loaded. State: LOADING → OPENING\n");
					// No OSD message here, will show "Ready" after OPENING
				}
				else if (!toc_thread_active) // Only retry if thread not currently running
				{
					// Failed, retry after 500ms
					load_timer = GetTimer(500);
					DebugLog("[MISTER] TOC load failed/retrying...\n");
				}
			}
			break;
			
		case PCD_OPENING:
			// Hold OPEN status briefly, then transition to STOP (door closed)
			if (!hasCDROMMedia(0))
			{
				cd_state = PCD_IDLE;
				load_attempted = false;
				DebugLog("[MISTER] State: OPENING → IDLE (media removed)\n");
				break;
			}
			
			if (CheckTimer(load_timer))
			{
				// Door "closed" - signal STOP (disc ready)
				cdd.status = CD_STAT_STOP;
				cdd.latency = 10; // Standard latency
				cd_state = PCD_READY;
				
				printf("[MISTER] State: OPENING → READY\n");
				printf("[MISTER] cdd.status = STOP (0x%02X) - door closed\n", cdd.status);
				Info("Ready", 10000); // Long timeout, will be cleared when BIOS requests TOC
				printf("[MISTER] BIOS should now detect disc and request TOC\n");
				DebugLog("[MISTER] State: OPENING → READY. Status = STOP. BIOS in control.\n");
			}
			break;
			
		case PCD_READY:
			// Media removed while ready
			if (!hasCDROMMedia(0))
			{
				cd_state = PCD_IDLE;
				load_attempted = false;
				DebugLog("[MISTER] State: READY → IDLE (media removed)\n");
			}
			// In READY state, BIOS controls everything via commands
			// We don't change status here - CommandExec() does it
			break;
		}
	}

	if (!poll_timer || CheckTimer(poll_timer))
	{
		if (!cdd.isData && cdd.status == CD_STAT_PLAY && cdd.latency == 0) {
			// Send audio sectors faster so buffer stays filled
			poll_timer = GetTimer(10);
			adj = 0;
		} else {
			poll_timer = GetTimer(13 + (!adj ? 1 : 0));
			if (++adj >= 3) adj = 0;
		}

		if (has_command) {
			spi_uio_cmd_cont(UIO_CD_SET);
			uint64_t s = cdd.GetStatus(0);
			spi_w((s >> 0) & 0xFFFF);
			spi_w((s >> 16) & 0xFFFF);
			spi_w(((s >> 32) & 0x00FF) | (cdd.isData ? 0x01 << 8 : 0x00 << 8));
			DisableIO();

			has_command = 0;

			// Log Status Sent to Core
			uint8_t status_byte = (uint8_t)(s & 0xFF);
			uint8_t stat0_mode = status_byte & 0xF;
			uint8_t stat1_rep = (status_byte >> 4) & 0xF;
			printf("[CORE] < SEND STATUS: 0x%02X (loaded=%d latency=%d)\n", 
				stat0_mode, cdd.loaded, cdd.latency);
			DebugLog("[CORE] < SEND STATUS_WORD: %04X (Mode: %X, Rep: %X, Full: %02X)\n",
				(int)(s & 0xFFFF), stat0_mode, stat1_rep, status_byte);
		}

		cdd.Update();
	}

	uint8_t req = spi_uio_cmd_cont(UIO_CD_GET);
	if (req != last_req)
	{
		last_req = req;

		spi_w(MCD_GET_CMD);

		uint16_t data_in[4];
		data_in[0] = spi_w(0);
		data_in[1] = spi_w(0);
		data_in[2] = spi_w(0);
		DisableIO();

		if (need_reset || data_in[0] == 0xFF) {
			printf("MCD: request to reset\n");
			DebugLog("[CORE] > REQUEST RESET\n");
			
			// If physical CD is loaded, unload it first (this will eject)
			if (cdd.loaded && cdd.IsPhysicalCD()) {
				printf("[MCD] Reset requested with physical CD - unloading and ejecting\n");
				DebugLog("[CORE] Reset with physical CD - calling Unload() to eject\n");
				cdd.Unload();
			}
			
			need_reset = 0;
			cdd.Reset();
		}

		uint64_t c = *((uint64_t*)(data_in));
		cdd.SetCommand(c, 0);

		// Log Command Received from Core
		printf("[CORE] > RECV COMMAND: 0x%02X\n", (int)(c & 0xFF));
		DebugLog("[CORE] > GET COMMAND: %02X (Arg: %02X)\n", (int)(c & 0xFF), (int)((c >> 8) & 0xFF));

		// Clear "Ready" message when BIOS requests TOC (enters "Checking Disc" state)
		uint8_t cmd = (uint8_t)(c & 0xFF);
		static bool toc_requested = false;
		if (cmd == 0x02 && !toc_requested) {  // CD_COMM_TOC
			toc_requested = true;
			Info("", 1);  // Clear OSD, BIOS shows "Checking Disc"
			printf("[MISTER] BIOS requested TOC - clearing OSD, BIOS in control\n");
		}
		else if (cmd != 0x02 && toc_requested) {
			toc_requested = false;  // Reset for next insertion
		}

		cdd.CommandExec();
		has_command = 1;

		//printf("\x1b[32mMCD: Get command, command = %04X%04X%04X, has_command = %u\n\x1b[0m", data_in[2], data_in[1], data_in[0], has_command);
	}
	else
		DisableIO();
}

static char buf[1024];
static void mcd_mount_save(const char *filename)
{
	user_io_set_index(SAVE_IO_INDEX);
	user_io_set_download(1);
	if (strlen(filename))
	{
		FileGenerateSavePath(filename, buf);
		user_io_file_mount(buf, 0, 1);
	}
	else
	{
		user_io_file_mount("");
	}
	user_io_set_download(0);
}

static int mcd_load_rom(const char *basename, const char *name, int sub_index)
{
	strcpy(buf, basename);
	char *p = strrchr(buf, '/');
	if (p)
	{
		p++;
		strcpy(p, name);
		if (user_io_file_tx(buf, sub_index << 6)) return 1;
	}

	return 0;
}

void mcd_set_image(int num, const char *filename, CDROM_TrackInfo* tracks, int track_count)
{
	static char last_dir[1024] = {};

	(void)num;

	cdd.Unload();
	cdd.status = CD_STAT_OPEN;

	int same_game = (*filename && *last_dir && !strncmp(last_dir, filename, strlen(last_dir))) || (!*filename && !*last_dir);
	strcpy(last_dir, filename);
	char *p = strrchr(last_dir, '/');
	if (p) *p = 0;

	int loaded = 1;
	if (!same_game)
	{
		mcd_mount_save("");

		user_io_status_set("[0]", 1);
		user_io_status_set("[0]", 0);
		mcd_reset();

		loaded = 0;
		strcpy(buf, last_dir);
		char *p = strrchr(buf, '/');
		if (p)
		{
			strcpy(p + 1, "cd_bios.rom");
			loaded = user_io_file_tx(buf);
		}
		else
		{
			// Fallback for physical CD/empty path: Try known regions
			const char *bios_paths[] = {"/media/fat/games/MegaCD/USA/cd_bios.rom",
			                            "/media/fat/games/MegaCD/Europe/cd_bios.rom",
			                            "/media/fat/games/MegaCD/Japan/cd_bios.rom",
			                            "/media/fat/games/MegaCD/boot.rom"};
			for (int i = 0; i < 4; i++)
			{
				strcpy(buf, bios_paths[i]);
				loaded = user_io_file_tx(buf);
				if (loaded) break;
			}
		}

		if (!loaded)
		{
			sprintf(buf, "%s/boot.rom", HomeDir());
			loaded = user_io_file_tx(buf);
		}

		if (!loaded) Info("CD BIOS not found!", 4000);
	}

	if (loaded && (*filename || hasCDROMMedia(0)))
	{
		int load_res = 0;
		if (tracks && track_count > 0)
		{
			// Explicit physical load from background thread
			load_res = cdd.LoadPhysical(tracks, track_count);
		}
		else
		{
			// Normal file load (or implicit physical check if supported by cdd.Load, currently disabled)
			load_res = cdd.Load(filename);
		}

		if (load_res > 0)
		{
			cdd.status = cdd.loaded ? CD_STAT_STOP : CD_STAT_NO_DISC;
			cdd.latency = 10;
			cdd.SendData = mcd_send_data;
			cdd.CanSendData = mcd_can_send_data;

			if (!same_game)
			{
				mcd_load_rom(filename, "cd_bios.rom", 0);
				mcd_load_rom(filename, "cart.rom", 1);
				mcd_mount_save(filename);
				cheats_init(filename, 0);
			}
		}
		else
		{
			cdd.status = CD_STAT_NO_DISC;
		}
	}
}

void mcd_reset() {
	need_reset = 1;
}

int mcd_send_data(uint8_t* buf, int len, uint8_t index) {
	// set index byte
	user_io_set_index(index);

	user_io_set_download(1);
	user_io_file_tx_data(buf, len);
	user_io_set_download(0);
	return 1;
}

